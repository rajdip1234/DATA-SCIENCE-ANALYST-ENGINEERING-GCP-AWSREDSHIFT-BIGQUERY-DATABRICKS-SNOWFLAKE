# ==========================================================
# 3. DATE AND CAMPAIGN CONFIGURATION
# ==========================================================

today = TEST_DATE if TEST_DATE else datetime.date.today()

print("Current Execution Date:", today.strftime("%d-%m-%Y"))

campaigns = {
    (20, 11): {
        "subject": "Black Friday Discount Offer",
        "body": "Do not wait! Grab your Black Friday discount offer now."
    },

    (20, 12): {
        "subject": "White Friday Discount Offer",
        "body": "Do not wait! Enjoy our special White Friday offer."
    },

    (5, 12): {
        "subject": "Discount Offer",
        "body": "Your discount offer is available now."
    }
}

actual_date = (today.day, today.month)
campaign = campaigns.get(actual_date)

# ==========================================================
# 4. INITIALIZE EXECUTION COUNTERS
# ==========================================================

total_customers = 0
prepared_emails = 0
successful_emails = 0
failed_emails = 0

# ==========================================================
# 5. CHECK CAMPAIGN AVAILABILITY
# ==========================================================

if campaign is None:

    print("\nNo email campaign is scheduled for this date.")

else:

    print("\nCampaign Selected:", campaign["subject"])

    # ======================================================
    # 6. READ EXCEL CUSTOMER DATA
    # ======================================================

    if not Path(EXCEL_FILE).is_file():
        raise FileNotFoundError(
            f"Excel file not found: {EXCEL_FILE}"
        )

    Emails_list = pd.read_excel(EXCEL_FILE)

    # Remove unnecessary spaces from column names
    Emails_list.columns = Emails_list.columns.astype(str).str.strip()

    required_columns = ["Name", "Email"]

    missing_columns = [
        col for col in required_columns
        if col not in Emails_list.columns
    ]

    if missing_columns:
        raise ValueError(
            f"Missing required columns: {missing_columns}"
        )

    # Select only required columns
    Emails_list = Emails_list[["Name", "Email"]].copy()

    # Remove missing values
    Emails_list = Emails_list.dropna(
        subset=["Name", "Email"]
    )

    # Clean customer records
    Emails_list["Name"] = (
        Emails_list["Name"].astype(str).str.strip()
    )

    Emails_list["Email"] = (
        Emails_list["Email"].astype(str).str.strip().str.lower()
    )

    # Remove empty records
    Emails_list = Emails_list[
        (Emails_list["Name"] != "") &
        (Emails_list["Email"] != "")
    ]

    # Remove duplicate email addresses
    Emails_list = Emails_list.drop_duplicates(
        subset=["Email"]
    )

    # Validate email addresses
    email_pattern = r"^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$"

    valid_mask = Emails_list["Email"].str.match(
        email_pattern, na=False
    )

    invalid_emails = Emails_list[~valid_mask]

    Emails_list = Emails_list[valid_mask].copy()

    total_customers = len(Emails_list)

    print("\nTotal Valid Customers:", total_customers)
    print("Invalid Email Records:", len(invalid_emails))

    if total_customers == 0:
        print("\nNo valid customer records found.")

    else:

        # ==================================================
        # 7. PREPARE PERSONALIZED EMAILS
        # ==================================================

        email_messages = []

        for row in Emails_list.itertuples(index=False):

            message = EmailMessage()

            message["From"] = (
                userdata.get("GMAIL_SENDER")
                if not DRY_RUN
                else "test@example.com"
            )

            message["To"] = row.Email
            message["Subject"] = campaign["subject"]

            message.set_content(
                f"Hi {row.Name},\n\n"
                f"{campaign['body']}\n\n"
                "Thank you."
            )

            email_messages.append(message)

            prepared_emails += 1

        print("\nPrepared Emails:", prepared_emails)

        # ==================================================
        # 8. DRY RUN OR ACTUAL EMAIL EXECUTION
        # ==================================================

        if DRY_RUN:

            print("\nDRY RUN MODE ENABLED")
            print("No actual emails will be sent.\n")

            for message in email_messages:

                print(
                    f"READY: {message['To']} | "
                    f"{message['Subject']}"
                )

        else:

            # Retrieve credentials from Colab Secrets
            Sender = userdata.get("GMAIL_SENDER")
            Password = userdata.get("GMAIL_APP_PASSWORD")

            if not Sender or not Password:
                raise ValueError(
                    "Gmail credentials are missing from Colab Secrets."
                )

            # Connect to Gmail SMTP server
            with smtplib.SMTP_SSL(
                SMTP_HOST,
                SMTP_PORT,
                timeout=30
            ) as connect_server:

                connect_server.login(Sender, Password)

                # Send individual emails
                for message in email_messages:

                    message.replace_header("From", Sender)

                    try:

                        refused = connect_server.send_message(message)

                        if refused:
                            failed_emails += 1
                            print(
                                f"FAILED: {message['To']} | "
                                f"Recipient rejected."
                            )

                        else:
                            successful_emails += 1

                            print(
                                f"SUCCESS: {message['To']}"
                            )

                    except Exception as error:

                        failed_emails += 1

                        print(
                            f"FAILED: {message['To']} | {error}"
                        )

